// Bundles the Mobile Wallet Adapter for the web (@solana-mobile/wallet-standard-mobile) into
// src/vendor/mwa-iife.js, served at /vendor/mwa.js. On Android (the Seeker included) it lets the
// pay page ask the phone's wallet app to pay, from the browser or the installed app.
// Only needed when changing the version. Usage (from telegram-bot/): node scripts/vendor-mwa.mjs
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const VERSION = "0.7.0";
const dir = mkdtempSync(join(tmpdir(), "mwa-"));
copyFileSync(new URL("./mwa-entry.js", import.meta.url), join(dir, "entry.js"));
execFileSync("npm", ["init", "-y"], { cwd: dir });
execFileSync("npm", ["install", "--no-audit", "--no-fund", `@solana-mobile/wallet-standard-mobile@${VERSION}`, "@wallet-standard/app@1", "esbuild@0.24.0"], { cwd: dir, stdio: "inherit" });
execFileSync(join(dir, "node_modules/.bin/esbuild"), ["entry.js", "--bundle", "--minify", "--format=iife", "--platform=browser", "--target=es2020", "--outfile=mwa.js"], { cwd: dir, stdio: "inherit" });
const js = readFileSync(join(dir, "mwa.js"), "utf8");
writeFileSync(new URL("../src/vendor/mwa-iife.js", import.meta.url),
  `// @solana-mobile/wallet-standard-mobile ${VERSION} (Apache-2.0, https://github.com/solana-mobile/mobile-wallet-adapter), browser build.\n` +
  `// Generated by scripts/vendor-mwa.mjs from scripts/mwa-entry.js. Do not edit by hand.\n` +
  `export const MWA_VERSION = ${JSON.stringify(VERSION)};\nexport const MWA_IIFE = ${JSON.stringify(js)};\n`);
console.log(`src/vendor/mwa-iife.js: wallet-standard-mobile ${VERSION}, ${js.length} bytes`);
