// Downloads @solana/web3.js (browser build) into src/vendor/web3-iife.js so the worker can
// serve it to the payment page at /vendor/web3.js. Only needed when changing the version.
// Usage (from telegram-bot/): node scripts/vendor-web3.mjs
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const VERSION = "1.98.4";
const dir = mkdtempSync(join(tmpdir(), "web3-"));
execFileSync("npm", ["pack", "--silent", `@solana/web3.js@${VERSION}`], { cwd: dir });
execFileSync("tar", ["xzf", `solana-web3.js-${VERSION}.tgz`], { cwd: dir });
const js = readFileSync(join(dir, "package/lib/index.iife.min.js"), "utf8");
writeFileSync(new URL("../src/vendor/web3-iife.js", import.meta.url),
  `// @solana/web3.js ${VERSION} (MIT, https://github.com/solana-labs/solana-web3.js), browser build.\n` +
  `// Generated by scripts/vendor-web3.mjs. Do not edit by hand.\n` +
  `export const WEB3_VERSION = ${JSON.stringify(VERSION)};\nexport const WEB3_IIFE = ${JSON.stringify(js)};\n`);
console.log(`src/vendor/web3-iife.js: @solana/web3.js ${VERSION}, ${js.length} bytes`);
